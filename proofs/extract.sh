#!/usr/bin/env bash
# Extract sudo-rs to Lean 4 with Charon + Aeneas into proofs/lean/SudoRs.
#
# Usage: proofs/extract.sh [extra charon args...]
#   e.g. proofs/extract.sh --start-from crate::sudoers::find_item
# Without arguments, Charon takes its options from `[package.metadata.charon]` in Cargo.toml.
#
# Environment:
#   SUDO_RS_SRC   crate root to extract from (default: this repository's root).
#   AENEAS_FLAGS  extra Aeneas flags (default: -loops-to-rec; set to "" for none). Always passed:
#                 -backend lean -split-files -subdir SudoRs -no-progress-bar.
#
# Run inside `nix develop` (provides pinned `charon` and `aeneas`).
# Exits non-zero if Charon fails or Aeneas reports any `[Error]`; the generated
# files are only installed after a clean run.
#
# lean/SudoRs/{Types,Funs}External.lean are hand-maintained models of external definitions:
# they are never overwritten, only seeded from Aeneas' *_Template.lean when missing. The script
# warns when a template declares a name the hand-maintained file lacks.
set -euo pipefail

proofs_dir=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
src=$(cd "${SUDO_RS_SRC:-$(dirname "$proofs_dir")}" && pwd)
lean_dir=$proofs_dir/lean
subdir=SudoRs
gen_dir=$lean_dir/$subdir
read -r -a aeneas_flags <<< "${AENEAS_FLAGS--loops-to-rec}"
header='-- THIS FILE WAS AUTOMATICALLY GENERATED BY AENEAS'

for tool in charon aeneas; do
  command -v "$tool" >/dev/null || { echo "extract.sh: '$tool' not on PATH; run inside 'nix develop'" >&2; exit 1; }
done

work=$(mktemp -d "${TMPDIR:-/tmp}/sudo-rs-extract.XXXXXX")
cleanup() { rm -rf "$work"; }
trap cleanup EXIT
fail() {
  echo "extract.sh: $1 (logs kept in $work)" >&2
  trap - EXIT
  exit 1
}

# Aeneas/Charon colour their output and redraw progress lines with '\r'.
plain() { sed -e 's/\x1b\[[0-9;?]*[A-Za-z]//g' | tr '\r' '\n'; }

echo "==> charon: $src"
toolchain=$(charon toolchain-path)
if ! (cd "$src" && PATH="$toolchain/bin:$PATH" \
      charon cargo --preset=aeneas "$@" --dest-file "$work/sudo_rs.llbc" -- --lib) \
      2>&1 | plain | tee "$work/charon.log"; then
  fail "charon failed"
fi
[ -f "$work/sudo_rs.llbc" ] || fail "charon produced no LLBC"

echo "==> aeneas ${aeneas_flags[*]}"
aeneas_status=0
aeneas -backend lean -split-files -subdir "$subdir" -no-progress-bar "${aeneas_flags[@]}" \
  "$work/sudo_rs.llbc" -dest "$work/out" 2>&1 | plain > "$work/aeneas.log" || aeneas_status=$?
grep -v -e '^\s*$' -e '^Post-processed translated' "$work/aeneas.log" || true

n_errors=$(grep -c '^\[Error\]' "$work/aeneas.log" || true)
if [ "$n_errors" -gt 0 ] || [ "$aeneas_status" -ne 0 ] || grep -q '^Fatal error' "$work/aeneas.log"; then
  echo >&2
  echo "==> Aeneas failed: exit status $aeneas_status, $n_errors [Error] report(s)" >&2
  echo "Errors by kind:" >&2
  { grep '^\[Error\]' "$work/aeneas.log" | sed 's/^\[Error\] *//' | sort | uniq -c | sort -rn; } >&2 || true
  { grep -o '^Fatal error: .\{0,160\}' "$work/aeneas.log" | sort | uniq -c; } >&2 || true
  echo "Definitions not translated:" >&2
  { grep -o "Could not translate the [a-z ]* '[^ ]*\|Could not translate [a-z ]* '[^ ]*" "$work/aeneas.log" \
      | sort | uniq -c | sort -rn; } >&2 || true
  fail "aeneas reported errors"
fi

out=$work/out/$subdir
[ -d "$out" ] || fail "aeneas produced no output in $out"

# Names introduced by top-level declarations (ignoring comments) whose keyword matches $1.
decl_names() {
  awk -v kw="$1" '
    {
      s = $0; line = ""
      while (s != "") {
        if (in_comment) {
          i = index(s, "-/"); if (!i) { s = ""; break }
          s = substr(s, i + 2); in_comment = 0
        } else {
          i = index(s, "/-"); if (!i) { line = line s; s = ""; break }
          line = line substr(s, 1, i - 1) " "; s = substr(s, i + 2); in_comment = 1
        }
      }
      sub(/--.*/, "", line)
      n = split(line, tok, /[[:space:]]+/)
      for (j = 1; j <= n; j++) {
        if (tok[j] == "") continue
        if (want) { print tok[j]; want = 0 } else if (tok[j] ~ kw) want = 1
      }
    }' "$2" | sort -u
}

echo "==> installing into ${gen_dir#"$proofs_dir/"}"
mkdir -p "$gen_dir"
# Replace every previously generated file (Aeneas header on line 1). The hand-maintained
# *External.lean models never carry that header, and Aeneas never emits files with their names.
for f in "$gen_dir"/*.lean; do
  [ -e "$f" ] || continue
  name=$(basename "$f")
  case $name in TypesExternal.lean | FunsExternal.lean) continue ;; esac
  [ "$(head -n 1 "$f")" = "$header" ] || continue
  if [[ $name == *_Template.lean ]] && [ -f "$out/$name" ] && ! cmp -s "$f" "$out/$name"; then
    echo "note: $name changed:" >&2
    diff -u "$f" "$out/$name" >&2 || true
  fi
  rm -- "$f"
done
cp -- "$out"/*.lean "$gen_dir"/

for model in "$gen_dir"/TypesExternal.lean "$gen_dir"/FunsExternal.lean; do
  t=${model%.lean}_Template.lean
  if [ ! -e "$t" ]; then
    [ -e "$model" ] && echo "note: $(basename "$model") is no longer imported by the generated code" >&2
    continue
  fi
  if [ ! -e "$model" ]; then
    # Seed from the template, dropping its "generated"/"rename me" header lines.
    {
      echo "-- Hand-maintained models of external definitions used by the generated code."
      echo "-- Seeded from $(basename "$t") by proofs/extract.sh; never overwritten by it."
      sed -e "1,3{/^$header\$/d;/^-- This is a template file/d}" "$t"
    } > "$model"
    echo "seeded $(basename "$model") from $(basename "$t")"
  fi
  missing=$(comm -23 <(decl_names '^axiom$' "$t") \
    <(decl_names '^(axiom|opaque|def|abbrev|structure|inductive|class|instance)$' "$model"))
  if [ -n "$missing" ]; then
    echo "WARNING: $(basename "$t") declares names missing from $(basename "$model"):" >&2
    printf '  %s\n' $missing >&2
  fi
done
ls -1 "$gen_dir"
